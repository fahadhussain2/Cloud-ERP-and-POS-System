import { randomBytes } from 'node:crypto';

// Request IDs (architecture §11.2): UUIDv7, sortable by time, shown to users as the error "reference".

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function newRequestId(): string {
  const b = randomBytes(16);
  b.writeUIntBE(Date.now(), 0, 6);
  b[6] = (b[6]! & 0x0f) | 0x70;
  b[8] = (b[8]! & 0x3f) | 0x80;
  const h = b.toString('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

/** A caller's ID is kept only if it is a UUID, so nothing else reaches the logs. */
export const isRequestId = (value: unknown): value is string => typeof value === 'string' && UUID.test(value);
